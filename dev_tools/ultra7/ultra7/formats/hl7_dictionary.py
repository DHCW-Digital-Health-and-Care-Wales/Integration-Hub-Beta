def describe_hl7(label: str) -> str:
    """Return a human-readable HL7 description for a segment, field, or component label."""
    normalized = _REP_SUFFIX_RE.sub("", label)
    if normalized in FIELD_NAMES:
        return FIELD_NAMES[normalized]
    if normalized in SEGMENT_NAMES:
        return SEGMENT_NAMES[normalized]
    return ""
